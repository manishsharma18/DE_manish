
-- Example assumes the standardized member rows have already been copied into MEMBER_STG.
-- Calculate age as of current date; missing DOB remains NULL.
UPDATE SKYPOINTS_DB.CURATED.MEMBER_STG
SET AGE = IFF(DATE_OF_BIRTH IS NULL, NULL,
    DATEDIFF(YEAR, DATE_OF_BIRTH, CURRENT_DATE())
      - IFF(DATEADD(YEAR, DATEDIFF(YEAR, DATE_OF_BIRTH, CURRENT_DATE()), DATE_OF_BIRTH) > CURRENT_DATE(), 1, 0)),
    STALE_MEMBER = IFF(LAST_FLIGHT_DATE IS NULL, NULL,
                       DATEDIFF(DAY, LAST_FLIGHT_DATE, CURRENT_DATE()) > 90);

-- Latest record wins. Prefer a source-system update timestamp/sequence.
-- INGESTED_AT is only a fallback and is not a perfect substitute for source recency.
MERGE INTO SKYPOINTS_DB.CURATED.MEMBER_CURRENT T
USING (
    SELECT *
    FROM SKYPOINTS_DB.CURATED.MEMBER_STG
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY SOURCE_UPDATED_AT DESC NULLS LAST,
                 INGESTED_AT DESC,
                 SOURCE_ROW_NUMBER DESC
    ) = 1
) S
ON T.MEMBER_ID = S.MEMBER_ID
WHEN MATCHED THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.LAST_FLIGHT_DATE = S.LAST_FLIGHT_DATE,
    T.TIER_CODE = S.TIER_CODE,
    T.AGENT_NAME = S.AGENT_NAME,
    T.STATE = S.STATE,
    T.COUNTRY = S.COUNTRY,
    T.POST_CODE = S.POST_CODE,
    T.DATE_OF_BIRTH = S.DATE_OF_BIRTH,
    T.IS_ACTIVE = S.IS_ACTIVE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.SOURCE_COUNTRY = S.SOURCE_COUNTRY,
    T.SOURCE_UPDATED_AT = S.SOURCE_UPDATED_AT,
    T.INGESTED_AT = S.INGESTED_AT,
    T.BATCH_ID = S.BATCH_ID
WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE,
    AGENT_NAME, STATE, COUNTRY, POST_CODE, DATE_OF_BIRTH, IS_ACTIVE, AGE,
    STALE_MEMBER, SOURCE_COUNTRY, SOURCE_UPDATED_AT, INGESTED_AT, BATCH_ID
) VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, S.ENROLLMENT_DATE, S.LAST_FLIGHT_DATE, S.TIER_CODE,
    S.AGENT_NAME, S.STATE, S.COUNTRY, S.POST_CODE, S.DATE_OF_BIRTH, S.IS_ACTIVE, S.AGE,
    S.STALE_MEMBER, S.SOURCE_COUNTRY, S.SOURCE_UPDATED_AT, S.INGESTED_AT, S.BATCH_ID
);

-- Rebuild country tables from canonical current state. This automatically removes a
-- member from the previous country after a country move.
TRUNCATE TABLE SKYPOINTS_DB.CURATED.TARGET_INDIA;
INSERT INTO SKYPOINTS_DB.CURATED.TARGET_INDIA
SELECT * FROM SKYPOINTS_DB.CURATED.MEMBER_CURRENT WHERE UPPER(COUNTRY) IN ('IND', 'INDIA');

TRUNCATE TABLE SKYPOINTS_DB.CURATED.TARGET_USA;
INSERT INTO SKYPOINTS_DB.CURATED.TARGET_USA
SELECT * FROM SKYPOINTS_DB.CURATED.MEMBER_CURRENT WHERE UPPER(COUNTRY) IN ('USA', 'US');

TRUNCATE TABLE SKYPOINTS_DB.CURATED.TARGET_AUS;
INSERT INTO SKYPOINTS_DB.CURATED.TARGET_AUS
SELECT * FROM SKYPOINTS_DB.CURATED.MEMBER_CURRENT WHERE UPPER(COUNTRY) IN ('AU', 'AUS', 'AUS');
