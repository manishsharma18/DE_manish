
CREATE DATABASE IF NOT EXISTS SKYPOINTS_DB;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_DB.RAW;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_DB.CURATED;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_DB.AUDIT;

CREATE OR REPLACE TABLE SKYPOINTS_DB.RAW.MEMBER_RAW (
    RAW_RECORD VARIANT,
    SOURCE_FILE VARCHAR,
    SOURCE_ROW_NUMBER NUMBER,
    SOURCE_COUNTRY VARCHAR(5),
    BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE SKYPOINTS_DB.RAW.REDEMPTION_RAW (
    RAW_PAYLOAD VARIANT,
    SOURCE_FILE VARCHAR,
    BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE SKYPOINTS_DB.CURATED.MEMBER_STG (
    MEMBER_ID VARCHAR(18),
    MEMBER_NAME VARCHAR(255),
    ENROLLMENT_DATE DATE,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE CHAR(5),
    AGENT_NAME VARCHAR(255),
    STATE CHAR(5),
    COUNTRY CHAR(5),
    POST_CODE VARCHAR(10),
    DATE_OF_BIRTH DATE,
    IS_ACTIVE CHAR(1),
    AGE NUMBER(3,0),
    STALE_MEMBER BOOLEAN,
    SOURCE_COUNTRY VARCHAR(5),
    SOURCE_FILE VARCHAR,
    SOURCE_ROW_NUMBER NUMBER,
    SOURCE_UPDATED_AT TIMESTAMP_NTZ,
    INGESTED_AT TIMESTAMP_NTZ,
    BATCH_ID VARCHAR
);

-- Canonical current state. The assessment says country-specific tables;
-- this canonical table makes country moves safe and auditable.
CREATE OR REPLACE TABLE SKYPOINTS_DB.CURATED.MEMBER_CURRENT (
    MEMBER_ID VARCHAR(18),
    MEMBER_NAME VARCHAR(255),
    ENROLLMENT_DATE DATE,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE CHAR(5),
    AGENT_NAME VARCHAR(255),
    STATE CHAR(5),
    COUNTRY CHAR(5),
    POST_CODE VARCHAR(10),
    DATE_OF_BIRTH DATE,
    IS_ACTIVE CHAR(1),
    AGE NUMBER(3,0),
    STALE_MEMBER BOOLEAN,
    SOURCE_COUNTRY VARCHAR(5),
    SOURCE_UPDATED_AT TIMESTAMP_NTZ,
    INGESTED_AT TIMESTAMP_NTZ,
    BATCH_ID VARCHAR
);

CREATE OR REPLACE TABLE SKYPOINTS_DB.CURATED.TARGET_INDIA LIKE SKYPOINTS_DB.CURATED.MEMBER_CURRENT;
CREATE OR REPLACE TABLE SKYPOINTS_DB.CURATED.TARGET_USA LIKE SKYPOINTS_DB.CURATED.MEMBER_CURRENT;
CREATE OR REPLACE TABLE SKYPOINTS_DB.CURATED.TARGET_AUS LIKE SKYPOINTS_DB.CURATED.MEMBER_CURRENT;

CREATE OR REPLACE TABLE SKYPOINTS_DB.CURATED.REDEMPTION_TXN (
    MEMBER_ID VARCHAR(18),
    FEED_DATE DATE,
    TXN_ID VARCHAR,
    TXN_DATE DATE,
    PARTNER VARCHAR,
    MILES_REDEEMED NUMBER(18,0),
    STATUS VARCHAR,
    SOURCE_FILE VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE SKYPOINTS_DB.AUDIT.MEMBER_REJECTS (
    RAW_RECORD VARIANT,
    SOURCE_FILE VARCHAR,
    SOURCE_ROW_NUMBER NUMBER,
    BATCH_ID VARCHAR,
    REJECT_REASON VARCHAR,
    REJECTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE SKYPOINTS_DB.AUDIT.DQ_RESULTS (
    BATCH_ID VARCHAR,
    CHECK_NAME VARCHAR,
    FAILED_COUNT NUMBER,
    CHECKED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
