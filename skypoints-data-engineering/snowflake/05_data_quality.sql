
-- Mandatory fields
SELECT COUNT(*) AS FAILED_MANDATORY_ROWS
FROM SKYPOINTS_DB.CURATED.MEMBER_STG
WHERE MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = ''
   OR MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = ''
   OR ENROLLMENT_DATE IS NULL;

-- Key uniqueness (within global member identity assumption)
SELECT MEMBER_ID, COUNT(*) AS ROW_COUNT
FROM SKYPOINTS_DB.CURATED.MEMBER_CURRENT
GROUP BY MEMBER_ID
HAVING COUNT(*) > 1;

-- Field length checks
SELECT *
FROM SKYPOINTS_DB.CURATED.MEMBER_STG
WHERE LENGTH(MEMBER_ID) > 18
   OR LENGTH(MEMBER_NAME) > 255
   OR LENGTH(TIER_CODE) > 5
   OR LENGTH(COUNTRY) > 5;

-- Business/date checks
SELECT *
FROM SKYPOINTS_DB.CURATED.MEMBER_STG
WHERE (DATE_OF_BIRTH IS NOT NULL AND DATE_OF_BIRTH >= ENROLLMENT_DATE)
   OR (LAST_FLIGHT_DATE IS NOT NULL AND LAST_FLIGHT_DATE < ENROLLMENT_DATE)
   OR ENROLLMENT_DATE > CURRENT_DATE()
   OR DATE_OF_BIRTH > CURRENT_DATE()
   OR (IS_ACTIVE IS NOT NULL AND IS_ACTIVE NOT IN ('A', 'I'));

-- Redemption checks
SELECT *
FROM SKYPOINTS_DB.CURATED.REDEMPTION_TXN
WHERE TXN_ID IS NULL
   OR MEMBER_ID IS NULL
   OR MILES_REDEEMED < 0
   OR STATUS NOT IN ('COMPLETED', 'PENDING', 'FAILED', 'CANCELLED');

-- Orphan redemption members
SELECT T.*
FROM SKYPOINTS_DB.CURATED.REDEMPTION_TXN T
LEFT JOIN SKYPOINTS_DB.CURATED.MEMBER_CURRENT M
  ON T.MEMBER_ID = M.MEMBER_ID
WHERE M.MEMBER_ID IS NULL;

-- Detect duplicate transactions
SELECT TXN_ID, COUNT(*) AS ROW_COUNT
FROM SKYPOINTS_DB.CURATED.REDEMPTION_TXN
GROUP BY TXN_ID
HAVING COUNT(*) > 1;
